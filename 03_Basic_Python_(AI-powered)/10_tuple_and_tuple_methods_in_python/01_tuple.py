# ******************** TUPLE ********************

# Tuple: Tuples are used to store multiple values in a single variable, similar to lists.

# The key difference is that tuples are immutable,
# which means their values cannot be changed after creation.

# Tuples are commonly used when the data should remain constant.

# Note:
# Tuples are created using parentheses ().

# Syntax:
# variable_name = (value1, value2, value3, ...)

# Example:
# 01).
items = ("chair", "pen", "mouse", 25, 2026)

print(items)

# Output:
# ('chair', 'pen', 'mouse', 25, 2026)