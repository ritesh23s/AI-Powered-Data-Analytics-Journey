# ******************** TUPLE REPETITION ********************

# Tuple Repetition: The * operator is used to repeat the elements of a tuple
# a specified number of times.

# Syntax:
# variable_name * number

# Example:
# 01).
items = ("pen", "book", "mouse")

repeated_items = items * 3

print(repeated_items)

# Output:
# ('pen', 'book', 'mouse', 'pen', 'book', 'mouse', 'pen', 'book', 'mouse')

# Note:
# The * operator creates a new tuple.
# It does not modify the original tuple.