# ******************** ACCESSING TUPLE ELEMENTS ********************

# Tuple elements are accessed using indexes, similar to accessing elements in a list.

# Syntax:
# variable_name[index]

# Example:
# 01).
fruits = ("mango", "apple", "banana", "orange")

print(fruits[3])

# Output: orange

print(fruits[2])

# Output: banana

# Note:
# Tuple indexing starts from 0.
# The first element is at index 0,
# the second element is at index 1, and so on.