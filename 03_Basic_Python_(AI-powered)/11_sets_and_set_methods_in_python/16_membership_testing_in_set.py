# ******************** MEMBERSHIP TESTING IN SET ********************

# The "in" keyword is used to check
# whether a value exists in a set.

# It returns a Boolean value:
# True or False

# Example:
# 01).
items = {"apple", "orange", "mango", 2026, 25, "banana"}

print(25 in items)

# Output:
# True

# Example:
# 02).
print("grapes" not in items)

# Output:
# True