# ******************** SET ********************

# Set: Sets are used to store multiple values in a single variable.

# A set does not allow duplicate values
# and does not maintain any specific order.

# Sets are commonly used when you want to store only unique elements.

# Syntax:
# variable_name = {value1, value2, value3, ...}

# Example:
# 01).
numbers = {1, 2, 3, 4}

names = {"Hemant", "Joy", "Umang"}

print(numbers)
# Output: {1, 2, 3, 4}

print(names)
# Output: {'Hemant', 'Joy', 'Umang'}

# Note:
# Sets do not allow duplicate elements.
# Sets do not maintain a specific order.
# Set elements cannot be accessed using indexes.


# Example:
# 02).
numbers = {1, 2, 2, 3, 3, 4, 4}

print(numbers)

# Output: {1, 2, 3, 4}

