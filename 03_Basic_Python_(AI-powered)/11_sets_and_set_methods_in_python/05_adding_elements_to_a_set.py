# ******************** ADDING ELEMENTS TO A SET ********************
# ******************** ADD() SET METHOD ********************

# add(): It is used to add a single element to a set.

# Syntax:
# variable_name.add(value)

# Example:
# 01).
items = {"apple", "mango", 2026, 2.56}

items.add("orange")

print(items)

# Possible Output:
# {2.56, 'mango', 2026, 'apple', 'orange'}

# Note:
# The add() method modifies the original set.
# It adds only one element at a time.
# The order of elements in a set is not guaranteed.
