# ******************************** COMPARISON OPERATORS ********************************
# Comparison Operators - Comparison operators compare two values and returns either True or False.
a = 5
b = 3

# **************** There are following types of Comparison Operators ****************
# 01). Equal to ( == ) - It returns true if both operands are equal. otherwise returns False
# Example - 
print("01). Equal to ( == )")
print(a == b)

print("")

# 02). Not Equal ( != ) - It returns True if operands are not equal. otherwise returns False
print("02). Not Equal ( != )")
print(a !=b)

# 03). Greater That ( > ) - Returs True if left operand is greated than right. otherwise returns False
print("03). Greater That ( > )")
print(a > b)

# 04). Less Than ( < ) - Returns True if left operands is less that right. otherwise returns False
print("04). Less Than ( < )")
print(a < b)

# 05). Greater Than or Equal ( >= ) - It returns True if left is greater than or equal to right. otherwise returns False
print("# 05). Greater than or Equal ( >= )")
print(a >= b)

# 06). Less Than or Equal ( <= ) - It returns True if left is less than or equal to right. otherwise returns False 
print("06). Less Than or Equal ( <= )")
print( a <= b)