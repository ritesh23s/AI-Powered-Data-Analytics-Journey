# ******************************** ARITHMETIC OPERATORS ********************************
# Arithmetic Operators  - Arthemetic operator are used to perform mathematical calculation

a = 20
b = 6

# **************** There are following types of Arithmetic Operators ****************
# 01). Addition (+) - Adds two numbers  
# Example - 
print("01). Addition:")
print (a + b)
                # Here , 
                #         a and b are operands
                #         + is operator        


# 02). Subtraction (-) - Subtracts two numbers
# Example - 
print("02). Subtraction:")
print(a - b)
                # Here , 
                #         a and b are operands
                #         - is operator


# 03). Multiplication (*) - Multiplies two numbers
# Example - 
print("03). Multiplication:")
print(a * b)
                # Here , 
                #         a and b are operands
                #         * is operator
                

# 04). Division (/) - Divides two numbers (special thing with devidion in python it always returns a float)
# Example - 
print("04). Division:")
print(a / b)
                # Here , 
                #         a and b are operands
                #         / is operator


# 05). Floor Division (//) - Floor Division Divides two numbers and returns a whole number.
# Note:
# 1)• For positive numbers, it returns the whole number before the decimal point, no matter whether the decimal part is .1, .5, .6, .8, or .9.
# 2)• For negative numbers, it returns the next smaller whole number.
# Example - 
print("05). Floor Division")
print(a // b)
print("Floor Division for Positive & Negative Number")
print(17//3) #for positive number
print(-17//3) #for negative number
                # Here , 
                #         a and b are operands
                #         // is operator


# 06). Modulus (remainder)(%) - It returns the remainder
# Example - 
print("06). Modulus(remainder)")
print(a % b)
                # Here , 
                #         a and b are operands
                #         % is operator


# 07). (Exponentiation) Exponent (**) - Raises a number to the power of another number.
# Example - 
print("07). Exponent:")
print(2**3)
print(a ** b)
                # Here , 
                #         a and b are operands
                #         ** is operator