# ******************************** LOGICAL OPERATORS ********************************
# Logical Operators - Logical operators are used to combine conditional statement.
# Logical operators are used to combine tow or more conditios and reterns 
# a boolean value (True or False)

# Example - 
a = 10
b = 15
print (a < b and b > a)
print(a > b or b > a)
print(not a == 10)

# ****************** There are following types of logical operator ******************
# 01). Logical AND (&&) Operator - Its returns True if both condition are true

# 02). Logical OR (//) Operator - Its returns True when atleast one conditions
# is true. if both conditions is false then returns false.

# 03). Logical NOT (!) Operator - Its returns always reverse value of any expression and its works on single expression

