# ***************************** BITWISE OPERATORS *****************************
# Bitwise Operators: Bitwise operators work on binary repersentations of numbers
# There are multiple type of Bitwise operators
# -------------------------------------------
# |Operator           |         Description |
# --------------------|----------------------
# |  &                |             AND     |
# --------------------|----------------------
# |  \|               |              OR     |
# --------------------|----------------------
# |  ^                |             XOR     |
# --------------------|----------------------
# |  ~                |             NOT     |
# --------------------|----------------------
# |  <<               |         Left shift  |
# --------------------|----------------------
# |  >>               |         Right shift |
# -------------------------------------------

# Note:- They are mainly used in low-level programming, networking, cryptography,
# embedded systems, and sometimes for performance optimization.


# Exanple:
a = 5
b = 3
print(a & b)
