# ***************************** MEMBERSHIP OPERATORS *****************************
# 01). in membership operator: Its returns "True" if a specified value is founded within a sequence (like a list, tuple, or string).
# Example:
# 01).
name = "Shubham"
print("S" in name)

# 02).
village = "Kachnar"
print("z" in village)

