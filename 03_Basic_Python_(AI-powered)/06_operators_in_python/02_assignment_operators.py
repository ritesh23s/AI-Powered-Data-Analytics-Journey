# ******************************** ASSIGNMENT OPERATORS ********************************
# Assignment Operators - Assignment operators are used to assign values to variable
# Assignment operators are used to assign value to variables compound 
# assignment operators combine an arithmetic operator with assignment. 
# making code concise


# **************** There are following types of Assignment Operators **************
# Example - 

# 01) Assign the value ( = )
print("01) Assign the value ( x = 10 )")
x = 10
print(x)

# 02). Add and assign (+=) 
print("02). Add and assign ( x += 5 )")
x += 5 
print(x)

# 03) Subtract and assign ( -= )
print("03) Subtract and assign ( x -= 2 )")
x -= 2
print(x)

# 04). Multiply and assign ( *= )
print("04). Multiply and assign ( x *= 8)")
x *= 8
print(x)

# 05). Divide and assign ( /=)
print("05). Divide and assign ( x/= 3)")
x/= 3
print(x)

# 06). Floor divide and assign ( //= )
print("Floor divide and assign ( x //= 2)")
x //= 2
print(x)

# 07). Modulus and assign ( %= )
print("07). Modulus and assign ( x %= 3)")
x %= 3
print(x)

# 08). Exponent and assign ( **= )
print("08). Exponent and assign ( x **= 3)")
x **= 3
print(x)


