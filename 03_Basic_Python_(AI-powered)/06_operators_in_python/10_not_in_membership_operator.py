# ***************************** MEMBERSHIP OPERATORS *****************************
# 02). not in membership operator: Its returns "True" if a specified value is NOT found within the sequence. 
# Example:
# 01).
name = "Shubham"
print("z" not in name)

# 02).
village = "Kachnar"
print("K" not in village)

# 03). Example with list
print("03). Example with list")

fruits = ["apple", "banana", "mango"]
print("banana" not in fruits)