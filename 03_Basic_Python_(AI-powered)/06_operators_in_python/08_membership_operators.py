# ***************************** MEMBERSHIP OPERATORS *****************************
print("MEMBERSHIP OPERATORS")
# Membership Operators - Membership operator is a special operator in python.
# It is used to test whether a value exists in a sequence.

# There are two types of Membership Operators
# 01). in
# 02). not it 

# Example:
# 01).
name = "shubh"
print ("s" in name)

print("s" not in name)
