# 01). Built-in function
# 02). User-define function

# 01). Built-in function: these function are defined and pre-coded in python.

# some examples of built-in function are as follows:
# min(), max(), len(), sum(), type(), range(), dict(), list(), tuple(), set()
# print() etc.


# 02). User-define function: we can create functions to perform specific tasks
# as per our needs. such functions are called user-define functions.

