# *************** INDENTATION IN CONDITIONALS ***************

# Python uses indentation to define code blocks.
# The code inside a conditional block must have the same indentation.

# In simple language:

# Python uses spaces at the beginning of a line
# to show which code belongs to a conditional block.

# The code inside the if block must be written
# with spaces before it.

# Example:
if True:
    print("This runs")
    print("This also runs")

# Output:
# This runs
# This also runs


# Incorrect:
# if True:
# print("This runs")

# Error:
# IndentationError


# Note:
# Usually, 4 spaces are used before the code
# inside an if, elif, or else block.
