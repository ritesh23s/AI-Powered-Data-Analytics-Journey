# ******************** DICTIONARIES IN PYTHON ********************

# Dictionary: A dictionary is used to store data
# in key-value pairs.

# Each key is connected to a value.
# We use the key to access its corresponding value.

# Dictionaries are one of the most commonly used
# data structures in Python.

# Example:
# 01).
student = {
    "name": "Shubham",
    "roll_no": 25,
    "age": 23,
    "branch": "CSE"
}

print(student)

# Output:
# {'name': 'Shubham', 'roll_no': 25, 'age': 23, 'branch': 'CSE'}