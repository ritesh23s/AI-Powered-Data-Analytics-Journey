# ******************** CHECKING MEMBERSHIP ********************

# The "in" keyword is used to check whether an element exists in a list.

# It returns a Boolean value:
# True or False

# If the element is found, it returns True.
# Otherwise, it returns False.

# Syntax:
# value in variable_name

# Example:
# 01).
items = ["apple", "banana", "mango", "orange"]

print("banana" in items)

# Output:
# True


# Example:
# 02).
print("grapes" in items)

# Output:
# False