# ***************** LIST LENGTH *****************

# List Length: The len() function is used to get the number of elements in a list.

# Syntax:
# len(variable_name)

# Example:
# 01).
items = ["apple", "banana", "orange", "mango", 2026, 8, 5, 3.5454, False]

print(len(items))

# Output:
# 9

# Note:
# The len() function counts all elements in the list,
# regardless of their data types.