# ******************** CLEAR() LIST METHOD ********************

# clear(): It is used to remove all elements from a list.

# Syntax:
# variable_name.clear()

# Example:
# 01).
items = ["pen", "copy", "books", "keyboard", "mouse"]

print("Original List:", items)

items.clear()

print("Cleared List:", items)

# Output:
# Original List: ['pen', 'copy', 'books', 'keyboard', 'mouse']
# Cleared List: []

# Note:
# The clear() method modifies the original list.
# After using clear(), the list becomes empty.