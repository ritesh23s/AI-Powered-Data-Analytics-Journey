# ******************** INSERT() LIST METHOD ********************

# insert(): It is used to insert an element at a specific index in a list.

# Syntax:
# variable_name.insert(index, value)

# Example:
# 01).
cars = ["XUV", "BMW", "Audi", "Scorpio", "Verna"]

cars.insert(3, "Bolero")

print(cars)

# Output:
# ['XUV', 'BMW', 'Audi', 'Bolero', 'Scorpio', 'Verna']

# Note:
# The insert() method modifies the original list.
# It does not create a new list.