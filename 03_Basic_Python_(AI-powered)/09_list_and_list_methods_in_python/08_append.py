# ******************** APPEND() LIST METHOD ********************

# append(): It is used to add an element to the end of a list.

# Syntax:
# variable_name.append(value)

# Example:
# 01).
movies = ["bahubali", "war", "RRR"]
movies.append("baagi")
print(movies)
# Output:
# ['bahubali', 'war', 'RRR', 'baagi']

# Note:
# The append() method modifies the original list.
# It does not create a new list.
# The append() method returns None.

