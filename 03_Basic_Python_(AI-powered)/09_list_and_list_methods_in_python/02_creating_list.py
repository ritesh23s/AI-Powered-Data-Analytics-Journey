# ************** CREATING LIST **************

# Creating List: Lists are created using square brackets [].

# Example:
# 01).
my_list = ["Shubham", 25, 4, 2002]

print(my_list)

# Output:
# ['Shubham', 25, 4, 2002]


# 02).
# A list can store different types of data.

mixed_list = ["Kachnar", 196, 2.5, True]

print(mixed_list)

# Output:
# ['Kachnar', 196, 2.5, True]

# Note:
# A list can store strings, integers, floats,
# booleans, and many other data types together.