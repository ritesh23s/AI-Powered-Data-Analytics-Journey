# ***************** NEGATIVE INDEXING *****************

# Negative Indexing: Negative indexes are used to access elements from the end of the list.
# Negative indexing starts from -1.

# Syntax:
# variable_name[-index]

# Example:
# 01).
items = ["apple", "banana", "orange", "mango"]

print(items[-2])
# Output: orange

print(items[-1])
# Output: mango

print(items[-4])
# Output: apple