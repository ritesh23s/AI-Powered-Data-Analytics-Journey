# *************** STRING LENGTH ***************
# String length: We can find the length of a string using the "len()" function

# syntax:
# len(variable_name)

# Example:
# 01).
name = "Shubham"
name_length = len(name)

print("Name:", name)
print("Length:", name_length)

# Note:
# The len() function counts every character in a string,
# including letters, numbers, symbols, and spaces.