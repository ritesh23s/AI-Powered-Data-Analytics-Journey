# ******************** LOWER() AND UPPER() STRING METHODS ********************

print("01). lower()")
# 01). lower(): It is used to convert all characters of a string into lowercase.

# Syntax:
# variable_name.lower()

# Example 01):
text = "PYTHON"

print("Original String:", text)
print("Lowercase String:", text.lower())


print("02). upper()")
# 02). upper(): It is used to convert all characters of a string into uppercase.

# Syntax:
# variable_name.upper()

# Example 01):
name = "shubham"


print("Original String:", name)
print("Uppercase String:", name.upper())


# Note: 
# Both lower() and upper() always return a new string.
# They do not change the original string.