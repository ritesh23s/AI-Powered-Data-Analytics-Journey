# *************** STRING CONCATENATION ***************

# String Concatenation: It is used to combine two or more strings
# using the + operator.

# Syntax:
# string_01 + string_02 + string_03 + ... + string_n

# Example:
# 01).
name = "Dravin"
nickname = "Bokachoda"

result = name + " " + nickname

print(result)

# Output:
# Dravin Bokachoda