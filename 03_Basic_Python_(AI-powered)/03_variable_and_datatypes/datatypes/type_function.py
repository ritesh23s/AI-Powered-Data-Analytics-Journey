# Type Function = With the help of type() function we can check the data type of any variable or thing

name = "shubh"
age = 23
rating = 3.5
is_vote = True
details = {"Name": "Shubham","Age": 23, "Roll No.": 25}
favoritfruits = ["Banana", "Mango", "Apple", 56]

print(type(name))
print(type(age))
print(type(rating))
print(type(is_vote))

print(details)
print(type(details))

print(favoritfruits)
print(type(favoritfruits))
