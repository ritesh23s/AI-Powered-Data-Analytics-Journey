# ************* WHILE LOOPS IN PYTHON *************

# while loop: The while loop runs as a condition remains true.


# Syntax:

# variable_name = initial_value
# while condition:
#     do something
#     update variable


# Example:
# 01).
i = 1
while i <= 5:
    print(i)
    i += 1

# Output:
# 1
# 2
# 3
# 4
# 5

